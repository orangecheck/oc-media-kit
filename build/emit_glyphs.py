"""emit_glyphs — the normalized-glyph artifact for @orangecheck/design.

Renders every registered brand glyph (build/brands.py BRANDS) into a single
committed TypeScript module: 1024-canvas inner-SVG strings with __FG__ /
__BG__ / __INK__ color sentinels the consumer substitutes at runtime
(currentColor for silhouettes, fg="none" wireframe mode via the same
sentinels). This is the ONLY sanctioned way glyph geometry crosses into the
design package — it bakes the centering / y-flip / scale transforms the
Python pipeline owns (the orangecheck § is raw DejaVu font coordinates;
copying its d-string verbatim renders upside-down), so TS never re-derives
them and cannot drift silently.

Regenerate after any brands.py change:

    python3 build/emit_glyphs.py

Output: dist/glyphs/glyphs.ts (committed; vendored into
oc-packages/design/src/tokens/glyphs.ts — keep the two in sync, the design
repo's scripts/check-glyph-drift.mjs diffs them when the sibling checkout
exists).
"""
from __future__ import annotations

import hashlib
import pathlib

from brands import BRANDS

FG, BG, INK = "__FG__", "__BG__", "__INK__"
OUT = pathlib.Path(__file__).resolve().parent.parent / "dist" / "glyphs" / "glyphs.ts"


def main() -> None:
    entries: list[tuple[str, str]] = []
    for brand in BRANDS:
        inner = brand.glyph(FG, BG, INK, 1024)
        if "`" in inner or "${" in inner:  # would break the TS template literal
            raise ValueError(f"glyph '{brand.slug}' contains TS-hostile characters")
        entries.append((brand.slug, inner))

    digest = hashlib.sha256("".join(f"{s}:{g}" for s, g in entries).encode()).hexdigest()[:16]
    slugs = " | ".join(f"'{s}'" for s, _ in entries)
    body = ",\n".join(f"    {s}: `{g}`" for s, g in entries)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// GENERATED by oc-media-kit/build/emit_glyphs.py — DO NOT EDIT.\n"
        "// Regenerate: python3 build/emit_glyphs.py  ·  then re-vendor into\n"
        "// oc-packages/design/src/tokens/glyphs.ts (check-glyph-drift.mjs diffs them).\n"
        f"// source-digest: {digest}\n"
        "\n"
        "/** Inner-SVG markup per brand, normalized to a 0..1024 canvas with the\n"
        " *  pipeline's centering/flip/scale baked in. Colors are sentinels —\n"
        " *  substitute __FG__ / __BG__ / __INK__ (fg '__FG__'→'none' flips the\n"
        " *  outline-capable glyphs to wireframe mode). */\n"
        f"export type OcGlyphSlug = {slugs};\n"
        "\n"
        "export const OC_GLYPH_CANVAS = 1024;\n"
        "\n"
        "export const OC_GLYPHS: Record<OcGlyphSlug, string> = {\n"
        f"{body},\n"
        "};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(OUT.parents[2])} · {len(entries)} glyphs · digest {digest}")


if __name__ == "__main__":
    main()
